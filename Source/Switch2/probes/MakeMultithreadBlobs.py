# EXPERIMENT (multithreading Task 0): assembles probes/MultithreadBlobs.S with the build machine's x86-64 `as` and writes a
# header with the flat code bytes and the offset of every global symbol.
# Usage: MakeMultithreadBlobs.py <source.S> <work dir> <header out>
import os
import subprocess
import sys

Source, Work, Header = sys.argv[1:4]
os.makedirs(Work, exist_ok=True)
Object = os.path.join(Work, "MultithreadBlobs.o")
Flat = os.path.join(Work, "MultithreadBlobs.bin")
subprocess.run(["as", "--64", "-o", Object, Source], check=True)
# The blob is copied flat: a relocation would be left unresolved (a call to a global symbol assembles as `e8 00 00 00 00`).
Relocations = subprocess.run(["objdump", "-r", Object], check=True, capture_output=True, text=True).stdout
if "R_X86_64" in Relocations:
    sys.exit("MultithreadBlobs.S has relocations; use local labels:\n" + Relocations)
subprocess.run(["objcopy", "-O", "binary", "-j", ".text", Object, Flat], check=True)
Symbols = {}
for Line in subprocess.run(["nm", "--defined-only", Object], check=True, capture_output=True, text=True).stdout.splitlines():
    Parts = Line.split()
    if len(Parts) == 3 and Parts[1] == "T":
        Symbols[Parts[2]] = int(Parts[0], 16)
Bytes = open(Flat, "rb").read()
with open(Header, "w") as Out:
    Out.write("// Generated by probes/MakeMultithreadBlobs.py from probes/MultithreadBlobs.S. Do not edit.\n#pragma once\n#include <cstddef>\n#include <cstdint>\n\n")
    Out.write("namespace MtBlobs {\n")
    Out.write("alignas(16) inline constexpr uint8_t Code[] = {\n")
    for Start in range(0, len(Bytes), 16):
        Out.write("  " + ", ".join("0x%02x" % B for B in Bytes[Start:Start + 16]) + ",\n")
    Out.write("};\n")
    for Name, Offset in sorted(Symbols.items(), key=lambda Item: Item[1]):
        Out.write("inline constexpr size_t %s = 0x%x;\n" % (Name, Offset))
    Out.write("} // namespace MtBlobs\n")
